import { pixelPainter } from './pixelPainter';

type Colors = readonly [deep: string, mid: string, light: string, highlight: string];
type Design = {
  cloth: Colors;
  skin: Colors;
  hair: Colors;
  trim: string;
  kind: 'shield' | 'tide' | 'gate' | 'crown';
};

const designs: Record<string, Design> = {
  'blue-3': { kind: 'shield', cloth: ['#213747', '#376969', '#65a49a', '#a8d3bf'],
    skin: ['#683f43', '#af6e61', '#dc9c75', '#f1c396'], hair: ['#302737', '#49404a', '#75636b', '#ab8b80'], trim: '#e8c483' },
  'blue-4': { kind: 'tide', cloth: ['#40324a', '#806043', '#be8b50', '#f2c88b'],
    skin: ['#68454b', '#a97560', '#d89c70', '#f3c79c'], hair: ['#263348', '#394d63', '#5d7a88', '#90a7a4'], trim: '#8ce4e8' },
  'red-3': { kind: 'gate', cloth: ['#362735', '#68424c', '#a06b60', '#df9d7c'],
    skin: ['#654047', '#a46857', '#cd8a69', '#f0b288'], hair: ['#312837', '#4c3540', '#785059', '#ac7472'], trim: '#e3a56c' },
  'red-4': { kind: 'crown', cloth: ['#33243e', '#6e3653', '#ad5372', '#e2909d'],
    skin: ['#634056', '#a46972', '#d29785', '#f5c1a7'], hair: ['#302339', '#54364f', '#8a5b71', '#b18891'], trim: '#ffce76' },
};

export function createLatePortrait(id: string): HTMLCanvasElement | undefined {
  const design = designs[id];
  if (!design) return;
  const canvas = document.createElement('canvas');
  canvas.width = canvas.height = 64;
  const { pixel: p, shape: s } = pixelPainter(canvas.getContext('2d')!);
  const ink = '#202437';
  const [deep, mid, light, pale] = design.cloth;
  const [skinDark, shade, skin, shine] = design.skin;
  const [root, hair, streak, hairLight] = design.hair;

  s(ink, [0, 64], [4, 55], [13, 48], [19, 45], [16, 36], [14, 23],
    [17, 14], [25, 7], [40, 7], [49, 14], [52, 23], [51, 36],
    [46, 47], [58, 53], [64, 61], [64, 64]);
  s(deep, [2, 64], [6, 56], [16, 50], [26, 47], [42, 47], [55, 53], [62, 61], [63, 64]);
  s(mid, [6, 64], [10, 56], [20, 52], [25, 51], [33, 55], [44, 49], [53, 53], [57, 59],
    [54, 64], [43, 64], [42, 57], [36, 61], [29, 59], [24, 55], [15, 61], [14, 64]);
  s(light, [7, 59], [12, 54], [21, 51], [25, 52], [20, 55], [12, 58], [9, 61]);
  s(light, [47, 50], [54, 53], [59, 57], [58, 60], [53, 56], [48, 54]);
  p(13, 56, 5, 1, pale); p(49, 53, 4, 1, pale);
  s(skinDark, [26, 38], [42, 39], [45, 48], [36, 55], [26, 49]);
  s(shade, [30, 41], [40, 41], [41, 48], [35, 52], [29, 48]);
  s(root, [15, 29], [17, 18], [21, 12], [29, 8], [39, 8], [47, 13],
    [51, 20], [49, 32], [44, 35], [40, 40], [23, 45], [18, 40]);
  s(shade, [23, 25], [25, 18], [38, 13], [47, 20], [49, 27], [51, 31],
    [48, 34], [47, 41], [42, 47], [34, 48], [26, 43], [23, 37], [20, 35], [20, 29]);
  s(skin, [26, 23], [29, 18], [39, 15], [46, 21], [46, 28], [49, 32], [46, 34],
    [46, 39], [42, 44], [35, 45], [30, 41], [27, 36]);
  s(shine, [30, 22], [37, 17], [43, 19], [45, 23], [41, 24], [34, 24], [30, 27]);
  s(shine, [33, 32], [39, 30], [44, 31], [43, 34], [35, 36]);
  p(31, 26, 6, 2, root); p(32, 28, 4, 1, ink); p(34, 29, 2, 2, deep);
  p(43, 26, 4, 1, root); p(44, 28, 3, 1, ink);
  p(45, 32, 3, 1, shine); p(42, 35, 4, 1, shade); p(37, 40, 7, 1, skinDark);
  p(39, 42, 3, 1, shade);
  s(hair, [16, 26], [18, 17], [23, 12], [30, 9], [41, 11], [47, 16], [47, 22],
    [43, 19], [40, 16], [35, 21], [29, 24], [27, 34], [24, 36], [24, 28], [21, 25]);
  s(streak, [19, 19], [24, 13], [31, 11], [39, 13], [35, 16], [28, 18], [24, 23]);
  p(26, 14, 6, 1, hairLight); p(22, 18, 3, 1, hairLight);

  if (design.kind === 'shield' || design.kind === 'gate') {
    const gate = design.kind === 'gate';
    s(ink, [12, 28], [14, 18], [20, 9], [28, 5], [40, 5], [50, 11], [54, 19],
      [51, 24], [45, 22], [33, 23], [26, 26], [22, 38], [17, 42], [13, 37]);
    s(mid, [14, 29], [16, 19], [22, 10], [29, 7], [40, 7], [48, 12], [52, 19],
      [49, 22], [44, 20], [32, 21], [24, 25], [20, 38], [15, 37]);
    s(light, [17, 21], [23, 12], [31, 8], [39, 8], [43, 10], [36, 13], [26, 15], [21, 22]);
    p(29, 9, 8, 1, pale); p(18, 29, 2, 6, light); p(32, 20, 14, 1, design.trim);
    if (gate) {
      s(root, [24, 35], [29, 39], [36, 41], [47, 38], [46, 45], [41, 49], [33, 47], [26, 42]);
      p(34, 43, 8, 1, streak); p(23, 29, 2, 7, skinDark);
      p(43, 30, 2, 6, skinDark); p(44, 33, 1, 2, shine);
    } else {
      p(19, 40, 3, 5, design.trim); p(20, 41, 1, 3, pale);
      s(deep, [22, 46], [31, 51], [38, 53], [46, 47], [45, 52], [35, 58], [27, 54]);
      p(34, 54, 3, 3, design.trim);
    }
  } else if (design.kind === 'tide') {
    s(ink, [12, 30], [14, 21], [18, 16], [23, 14], [43, 13], [50, 17], [48, 22], [39, 20], [29, 22], [20, 24], [16, 30]);
    s(mid, [15, 27], [17, 21], [23, 16], [42, 15], [48, 18], [47, 20], [39, 18], [29, 20], [20, 23]);
    p(26, 17, 13, 1, pale); p(40, 16, 3, 3, design.trim); p(41, 16, 1, 1, '#edfaff');
    s(hair, [15, 31], [22, 27], [23, 36], [21, 46], [16, 53], [11, 54], [14, 47]);
    p(13, 50, 5, 2, streak); p(37, 53, 4, 4, design.trim);
  } else {
    s(ink, [15, 21], [13, 9], [20, 12], [24, 6], [30, 10], [36, 3], [43, 10],
      [50, 6], [51, 18], [48, 23], [39, 17], [29, 19], [20, 24]);
    s(design.trim, [16, 20], [15, 12], [21, 15], [25, 9], [31, 13], [36, 6], [42, 13],
      [48, 9], [49, 17], [47, 21], [39, 16], [29, 17], [20, 22]);
    p(34, 12, 5, 4, mid); p(36, 12, 2, 2, pale); p(20, 18, 7, 1, pale);
    s(root, [20, 34], [25, 37], [29, 44], [34, 48], [43, 45], [40, 50], [33, 52], [26, 47]);
    p(38, 43, 6, 1, streak); p(44, 32, 2, 1, skinDark);
  }
  return canvas;
}
